package com.ramkumar.lld.javareadiness.lldpatterns.practice;

import java.util.*;

/**
 * Practice Exercise — Phase 4 Java Readiness | 4.2 Recurring LLD Patterns (size S, lite: 6 TODOs)
 * Scenario B: Parcel Locker Service
 *
 * ═══════════════════════════════════════════════════════════════════════
 * PROBLEM STATEMENT
 * ═══════════════════════════════════════════════════════════════════════
 *
 * A parcel locker station receives parcels for recipients, who later collect them.
 * Build the in-memory service using the standard LLD skeleton:
 * entity → repository → service. Ids are generated by the service.
 *
 * ── CLASS: Parcel ──────────────────────────────────────────────────────
 *   Fields:
 *     1. String  id           (final)
 *     2. String  recipient    (final)
 *     3. int     weightGrams  (final)
 *     4. boolean pickedUp     (mutable; starts false — the ONLY mutable field)
 *   Constructor:
 *     1. Parcel(String id, String recipient, int weightGrams)
 *        Validate in THIS order, then assign:
 *          id null or blank      → IllegalArgumentException("id must not be blank")
 *          recipient == null     → NullPointerException("recipient must not be null")
 *          recipient blank       → IllegalArgumentException("recipient must not be blank")
 *          weightGrams <= 0      → IllegalArgumentException("weightGrams must be > 0")
 *   Methods:
 *     1. getId(), getRecipient(), getWeightGrams(), isPickedUp()
 *     2. markPickedUp() — sets pickedUp to true (no validation)
 *     3. toString() → "<id>[<recipient>, <weightGrams>g, <WAITING|PICKED_UP>]"
 *        e.g.  PCL-0001[Asha, 500g, WAITING]
 *
 * ── CLASS: ParcelRepository  (storage only — no business rules) ────────
 *   Fields:
 *     1. a map of id → Parcel that remembers insertion order
 *   Methods:
 *     1. save(Parcel p)
 *          p == null           → NullPointerException("parcel must not be null")
 *          id already stored   → IllegalArgumentException("duplicate id: <id>")
 *     2. findById(String id) → Optional<Parcel>   (empty if unknown; never null)
 *     3. findAll() → List<Parcel>   insertion order; an unmodifiable SNAPSHOT
 *        (later saves must not appear in a list already returned)
 *
 * ── CLASS: ParcelLockerService ─────────────────────────────────────────
 *   Fields:
 *     1. a ParcelRepository (final)
 *     2. an int id counter — per instance, NOT static; starts at 0
 *   Methods:
 *     1. register(String recipient, int weightGrams) → Parcel
 *          id format: String.format("PCL-%04d", n)   n = 1, 2, 3 ...
 *          Builds a Parcel (its constructor validates), saves it, and returns it.
 *          If validation fails the counter must NOT advance (no burned ids).
 *          Print:  System.out.printf("[LockerService] registered %s for %s%n", id, recipient)
 *     2. pickUp(String id) → Parcel
 *          unknown id          → NoSuchElementException("parcel not found: <id>")
 *          already picked up   → IllegalStateException("parcel already picked up: <id>")
 *          otherwise mark it picked up
 *          Print:  System.out.printf("[LockerService] picked up %s%n", id)
 *          Return the parcel.
 *     3. pendingFor(String recipient) → List<Parcel>
 *          Parcels for that recipient that are NOT picked up, in registration
 *          order; unmodifiable; empty list if none.
 *
 * ── Design constraints ─────────────────────────────────────────────────
 *   - No static counter; no UUIDs.
 *   - No containsKey + get/put pairs; no returning null from lookups.
 *   - Never expose the repository's internal map or list.
 *   - Entity validates itself; service owns ids and state rules.
 *   - Do not modify main().
 */
public class ParcelLockerPractice {

    // ── Class shells (hierarchy given; everything inside is yours) ──

    static class Parcel {

        // ── TODO 1: Declare the 4 fields and the constructor of Parcel
        //    Fields: String id (private final), String recipient (private final),
        //            int weightGrams (private final), boolean pickedUp (private, mutable, starts false)
        //    Constructor Parcel(String id, String recipient, int weightGrams)
        //    Validate in this order, then assign the three final fields:
        //      id null or blank    → IllegalArgumentException("id must not be blank")
        //      recipient is null   → NullPointerException("recipient must not be null")
        //                            (use the JDK helper that throws NPE with a message)
        //      recipient blank     → IllegalArgumentException("recipient must not be blank")
        //      weightGrams <= 0    → IllegalArgumentException("weightGrams must be > 0")
        private final String id;
        private final String recipient;
        private final int weightGrams;
        private boolean pickedUp = false;

        public Parcel(String id, String recipient, int weightGrams){
            if(id == null || id.isBlank()) throw new IllegalArgumentException("id must not be blank");
            Objects.requireNonNull(recipient, "recipient must not be null");
            if(recipient.isBlank()) throw new IllegalArgumentException("recipient must not be blank");
            if(weightGrams <= 0 ) throw new IllegalArgumentException("weightGrams must be > 0");

            this.id = id;
            this.recipient = recipient;
            this.weightGrams = weightGrams;
        }

        // ── TODO 2: Methods of Parcel
        //    getId() → String, getRecipient() → String, getWeightGrams() → int, isPickedUp() → boolean
        //    markPickedUp() → void: sets pickedUp to true
        //    toString() → String: "<id>[<recipient>, <weightGrams>g, <WAITING|PICKED_UP>]"
        //      WAITING while pickedUp is false, PICKED_UP once true
        //      e.g. "PCL-0001[Asha, 500g, WAITING]"
        public int getWeightGrams() { return weightGrams; }
        public String getId() { return id; }
        public String getRecipient() { return recipient; }
        public boolean isPickedUp() { return pickedUp;}

        public void markPickedUp() { pickedUp = true; }

        public String toString() {
            return String.format("%s[%s, %dg, %s]", id, recipient, weightGrams, pickedUp ? "PICKED_UP" : "WAITING");
        }

    }

    static class ParcelRepository {

        // ── TODO 3: Field and save() of ParcelRepository
        //    Field: a private final Map<String, Parcel> keyed by parcel id that keeps
        //           insertion order (pick the right Map implementation)
        //    save(Parcel p) → void
        //      p == null → throw NullPointerException("parcel must not be null")
        //      id already stored → throw IllegalArgumentException("duplicate id: " + id)
        //      Use a single map call that stores only if absent and tells you whether
        //      something was already there (NOT containsKey followed by put)
        //      Otherwise store the parcel under its id
        private final Map<String, Parcel> store = new LinkedHashMap<>();

        public void save(Parcel p){
            Objects.requireNonNull(p, "parcel must not be null");

            if(store.putIfAbsent(p.getId(), p) != null){
                throw new IllegalArgumentException("duplicate id: " + p.getId());
            }
        }

        // ── TODO 4: findById() and findAll() of ParcelRepository
        //    findById(String id) → Optional<Parcel>
        //      Parcel if present, Optional.empty() if not; never return null
        //    findAll() → List<Parcel>
        //      All stored parcels in insertion order
        //      Must be an unmodifiable SNAPSHOT: adding to it throws UnsupportedOperationException,
        //      and parcels saved later do NOT appear in a list that was returned earlier
        //      Do not return the map's values() view directly
        public Optional<Parcel> findById(String id) { return Optional.ofNullable(store.get(id));}
        public List<Parcel> findAll() { return List.copyOf(store.values());}
    }

    static class ParcelLockerService {

        // ── TODO 5: Fields and register() of ParcelLockerService
        //    Fields: private final ParcelRepository (create it inline);
        //            private int counter — per instance, NOT static, starts at 0
        //    register(String recipient, int weightGrams) → Parcel
        //      Id format: String.format("PCL-%04d", n) with n = 1, 2, 3 ...
        //      Build the Parcel with the candidate id FIRST (its constructor validates).
        //      Only after it was built successfully, advance the counter. A failed call
        //      must not consume an id: after register("Asha", 0) throws, the next
        //      successful register still gets the id the failed call would have had.
        //      Save the parcel in the repository
        //      Print: System.out.printf("[LockerService] registered %s for %s%n", id, recipient)
        //      Return the parcel
        private final ParcelRepository parcelRepository = new ParcelRepository();
        private int counter = 0;

        public Parcel register(String recipient, int weightGrams) {
            String id = String.format("PCL-%04d", counter + 1);
            Parcel parcel = new Parcel(id, recipient, weightGrams);
            counter += 1;
            parcelRepository.save(parcel);
            System.out.printf("[LockerService] registered %s for %s%n", id, recipient);
            return parcel;
        }

        // ── TODO 6: pickUp() and pendingFor() of ParcelLockerService
        //    pickUp(String id) → Parcel
        //      Look the parcel up with the repository's Optional
        //      Not found → throw NoSuchElementException("parcel not found: " + id)
        //                  (use the Optional method that throws via a supplier, no isPresent/get)
        //      Already picked up → throw IllegalStateException("parcel already picked up: " + id)
        //      Otherwise mark it picked up
        //      Print: System.out.printf("[LockerService] picked up %s%n", id)
        //      Return the parcel
        //    pendingFor(String recipient) → List<Parcel>
        //      Parcels whose recipient equals the argument and that are not picked up,
        //      in registration order; unmodifiable; empty list when none match
        //      Build it from the repository's findAll() with a stream (no manual loop)
        public Parcel pickUp(String id){
            Parcel parcel = parcelRepository.findById(id).orElseThrow(() -> new NoSuchElementException("parcel not found: " + id));
            if(parcel.isPickedUp()) throw new IllegalStateException("parcel already picked up: " + id);
            parcel.markPickedUp();
            Print: System.out.printf("[LockerService] picked up %s%n", id);
            return parcel;
        }

        public List<Parcel> pendingFor(String recipient) {
            return parcelRepository.findAll().stream().filter(parcel -> !parcel.isPickedUp()).toList();
        }
    }

    // ══════════════════════════════════════════════════════════════════
    // DO NOT MODIFY main()
    // ══════════════════════════════════════════════════════════════════
    public static void main(String[] args) {
        // Uncomment each block after implementing the corresponding TODO.

        // ── Test 1: Parcel basics and toString (uncomment after TODO 1 and 2) ──
         Parcel p = new Parcel("PCL-0001", "Asha", 500);
         System.out.println(p);                               // expected: PCL-0001[Asha, 500g, WAITING]
         System.out.println(p.isPickedUp());                  // expected: false
         p.markPickedUp();
         System.out.println(p);                               // expected: PCL-0001[Asha, 500g, PICKED_UP]

        // ── Test 2: Parcel validation order and exception types (uncomment after TODO 1) ──
         String[] bad = {"id", "nullRecipient", "blankRecipient", "weight"};
         for (String which : bad) {
             try {
                 switch (which) {
                     case "id" -> new Parcel(" ", "Asha", 5);
                     case "nullRecipient" -> new Parcel("P-1", null, 5);
                     case "blankRecipient" -> new Parcel("P-1", "  ", 5);
                     default -> new Parcel("P-1", "Asha", 0);
                 }
             } catch (IllegalArgumentException | NullPointerException e) {
                 System.out.println(e.getClass().getSimpleName() + ": " + e.getMessage());
             }
         }
        // // expected (4 lines):
        // //   IllegalArgumentException: id must not be blank
        // //   NullPointerException: recipient must not be null
        // //   IllegalArgumentException: recipient must not be blank
        // //   IllegalArgumentException: weightGrams must be > 0

        // ── Test 3: repository save / findById / duplicates (uncomment after TODO 3 and 4) ──
         ParcelRepository repo = new ParcelRepository();
         repo.save(new Parcel("PCL-0001", "Asha", 500));
         System.out.println(repo.findById("PCL-0001").isPresent());   // expected: true
         System.out.println(repo.findById("PCL-0099").isPresent());   // expected: false
         try {
             repo.save(new Parcel("PCL-0001", "Ben", 100));
         } catch (IllegalArgumentException e) {
             System.out.println(e.getMessage());              // expected: duplicate id: PCL-0001
         }
         try {
             repo.save(null);
         } catch (NullPointerException e) {
             System.out.println(e.getMessage());              // expected: parcel must not be null
         }

        // ── Test 4: findAll is an unmodifiable snapshot (uncomment after TODO 4) ──
         List<Parcel> snapshot = repo.findAll();
         System.out.println(snapshot.size());                 // expected: 1
         try {
             snapshot.add(new Parcel("X", "Y", 1));
         } catch (UnsupportedOperationException e) {
             System.out.println("unmodifiable");              // expected: unmodifiable
         }
         repo.save(new Parcel("PCL-0002", "Ben", 100));
         System.out.println(snapshot.size());                 // expected: 1
         System.out.println(repo.findAll().size());           // expected: 2

        // ── Test 5: service register — ids and logging (uncomment after TODO 5) ──
         ParcelLockerService svc = new ParcelLockerService();
         Parcel a = svc.register("Asha", 500);                // expected print: [LockerService] registered PCL-0001 for Asha
         Parcel b = svc.register("Ben", 1200);                // expected print: [LockerService] registered PCL-0002 for Ben
         System.out.println(a.getId() + " " + b.getId());     // expected: PCL-0001 PCL-0002
         System.out.println(new ParcelLockerService().register("Cy", 10).getId());
        //                                                      // expected: PCL-0001 (counter is per instance)

        // ── Test 6: pickUp and its exceptions (uncomment after TODO 6) ──
         System.out.println(svc.pickUp("PCL-0001").isPickedUp());     // expected print: [LockerService] picked up PCL-0001, then: true
         try {
             svc.pickUp("PCL-0001");
         } catch (IllegalStateException e) {
             System.out.println(e.getMessage());              // expected: parcel already picked up: PCL-0001
         }
         try {
             svc.pickUp("PCL-0099");
         } catch (NoSuchElementException e) {
             System.out.println(e.getMessage());              // expected: parcel not found: PCL-0099
         }

        // ── Test 7: pendingFor (uncomment after TODO 6) ──
         svc.register("Asha", 300);                           // expected print: [LockerService] registered PCL-0003 for Asha
         System.out.println(svc.pendingFor("Asha").stream().map(Parcel::getId).toList());  // expected: [PCL-0003]
         System.out.println(svc.pendingFor("Ben").stream().map(Parcel::getId).toList());   // expected: [PCL-0002]
         System.out.println(svc.pendingFor("Zed"));           // expected: []
         try {
             svc.pendingFor("Ben").add(a);
         } catch (UnsupportedOperationException e) {
             System.out.println("unmodifiable");              // expected: unmodifiable
         }

        // ── Test 8: failed register must not burn an id (uncomment after TODO 5) ──
         try {
             svc.register("Dee", 0);
         } catch (IllegalArgumentException e) {
             System.out.println(e.getMessage());              // expected: weightGrams must be > 0
         }
         try {
             svc.register(null, 5);
         } catch (NullPointerException e) {
             System.out.println(e.getMessage());              // expected: recipient must not be null
         }
         System.out.println(svc.register("Dee", 50).getId()); // expected print: [LockerService] registered PCL-0004 for Dee, then: PCL-0004
    }
}

